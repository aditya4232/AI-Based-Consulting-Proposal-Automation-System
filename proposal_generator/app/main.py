@app.get("/ollama-status")
def ollama_status(url: str = Query(default="http://localhost:11434")):
    """Check if Ollama is reachable and return all installed models with cloud/local tag."""
    base, err = _validate_ollama_url(url)
    if err:
        return err

    try:
        resp = http_requests.get(f"{base}/api/tags", timeout=5)
        resp.raise_for_status()
        data = resp.json()
        all_models = data.get("models", [])
        models = [
            {
                "name": m["name"],
                "is_cloud": ":cloud" in m.get("name", ""),
                "size": m.get("size", 0),
                "size_gb": round(m.get("size", 0) / (1024**3), 2) if m.get("size", 0) > 1000 else 0,
                "modified_at": m.get("modified_at", ""),
                "family": m.get("details", {}).get("family", ""),
                "parameter_size": m.get("details", {}).get("parameter_size", ""),
                "quantization": m.get("details", {}).get("quantization_level", ""),
            }
            for m in all_models
        ]
        local_count = sum(1 for m in models if not m["is_cloud"])
        return {
            "connected": True,
            "url": base,
            "models": models,
            "model_count": local_count,
            "total_models_including_cloud": len(all_models),
        }
    except http_requests.exceptions.ConnectionError:
        return JSONResponse(status_code=503, content={"connected": False, "url": base, "models": [], "model_count": 0, "error": "Cannot connect to Ollama. Make sure it is running."})
    except Exception as e:
        return JSONResponse(status_code=503, content={"connected": False, "url": base, "models": [], "model_count": 0, "error": str(e)})


@app.post("/ollama-pull")
async def ollama_pull_model(model_name: str = Query(..., min_length=1), url: str = Query(default="http://localhost:11434")):
    """Trigger a model pull on Ollama (non-streaming, async). Returns success/failure."""
    base, err = _validate_ollama_url(url)
    if err:
        return err

    def _do_pull():
        resp = http_requests.post(
            f"{base}/api/pull",
            json={"name": model_name, "stream": False},
            timeout=600,
        )
        resp.raise_for_status()
        return resp

    log.info("Pulling Ollama model: %s", model_name)
    try:
        await asyncio.to_thread(_do_pull)
        return {"success": True, "model": model_name, "message": f"Model '{model_name}' pulled successfully."}
    except http_requests.exceptions.ConnectionError:
        return JSONResponse(status_code=503, content={"success": False, "error": "Cannot connect to Ollama."})
    except http_requests.exceptions.Timeout:
        return JSONResponse(status_code=504, content={"success": False, "error": "Model pull timed out. Try manually: ollama pull " + model_name})
    except Exception as e:
        return JSONResponse(status_code=500, content={"success": False, "error": str(e)})


@app.post("/generate-proposal", response_model=ProposalResponse)
def generate(data: ProposalRequest, background_tasks: BackgroundTasks):
    """Generate a structured consulting proposal (JSON response)."""
    log.info("Generating proposal: %s (%s, %d months)", data.project_title, data.industry, data.duration_months)

    provider_opts = {
        "provider": data.provider,
        "model": data.model,
        "api_key": data.api_key,
        "api_url": data.api_url,
    }
    
    prompt = build_prompt(data)
    expected_weeks = data.duration_months * 4
    sections = generate_proposal(prompt, expected_weeks=expected_weeks, provider_opts=provider_opts)

    cost_data = calculate_cost(data.duration_months, data.expected_users)
    team = estimate_team_composition(data.duration_months, data.expected_users, data.tech_stack)

    # Persist cost report files in background
    try:
        background_tasks.add_task(save_cost_report, cost_data)
    except Exception as e:
        log.warning("Failed to schedule cost report save: %s", e)

    return {
        "executive_summary": sections["executive_summary"],
        "technical_approach": sections["technical_approach"],
        "timeline": sections["timeline"],
        "estimated_cost": cost_data,
        "risk_assessment": sections["risk_assessment"],
        "deliverables": sections["deliverables"],
        "team_composition": team,
    }


@app.post("/download-proposal-pdf")
def download_pdf(data: ProposalRequest):
    """Generate and return the proposal as a downloadable PDF."""
    log.info("Generating PDF for: %s", data.project_title)

    provider_opts = {
        "provider": data.provider,
        "model": data.model,
        "api_key": data.api_key,
        "api_url": data.api_url,
    }

    prompt = build_prompt(data)
    expected_weeks = data.duration_months * 4
    sections = generate_proposal(prompt, expected_weeks=expected_weeks, provider_opts=provider_opts)
    cost_data = calculate_cost(data.duration_months, data.expected_users)
    team = estimate_team_composition(data.duration_months, data.expected_users, data.tech_stack)

    proposal_for_pdf = {
        "project_title": data.project_title,
        "client_name": data.client_name or "",
        "industry": data.industry,
        "duration_months": data.duration_months,
        "expected_users": data.expected_users,
        "tech_stack": data.tech_stack,
        "executive_summary": sections["executive_summary"],
        "technical_approach": sections["technical_approach"],
        "timeline": sections["timeline"],
        "estimated_cost": cost_data,
        "risk_assessment": sections["risk_assessment"],
        "deliverables": sections["deliverables"],
        "team_composition": team,
    }

    pdf_path = build_proposal_pdf(proposal_for_pdf)
    safe_title = data.project_title.replace(" ", "_").replace("/", "_")
    pdf_filename = os.path.basename(pdf_path)

    # Record in device session DB if device_id provided
    proposal_id = None
    if data.device_id:
        try:
            proposal_id = record_proposal(
                device_id=data.device_id,
                filename=pdf_filename,
                title=data.project_title,
                client=data.client_name or "",
                industry=data.industry,
                months=data.duration_months,
                users=data.expected_users,
                provider=data.provider or "ollama",
                model=data.model or "auto",
                sections=sections,
            )
        except Exception as e:
            log.warning("record_proposal failed: %s", e)

    extra_headers = {"Content-Disposition": f'attachment; filename="{safe_title}_Proposal.pdf"'}
    if proposal_id:
        extra_headers["X-Proposal-Id"] = str(proposal_id)
        extra_headers["Access-Control-Expose-Headers"] = "X-Proposal-Id"

    return FileResponse(
        path=pdf_path,
        media_type="application/pdf",
        filename=f"{safe_title}_Proposal.pdf",
        headers=extra_headers,
    )


