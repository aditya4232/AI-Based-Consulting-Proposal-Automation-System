@app.get("/session/{device_id}")
def session_info(device_id: str):
    """Return device info and proposal history for persistence across sessions."""
    info = get_device_info(device_id)
    if not info:
        raise HTTPException(status_code=404, detail="Device not registered")
    history = get_device_proposals(device_id)
    return {"device": info, "history": history}


@app.get("/session/{device_id}/proposals")
def session_proposals(device_id: str):
    """List proposals generated by this device with file size info."""
    rows = get_device_proposals(device_id)
    output_dir = settings.output_dir
    result = []
    for r in rows:
        fp = os.path.join(output_dir, r["filename"])
        size_kb = round(os.path.getsize(fp) / 1024, 1) if os.path.isfile(fp) else 0
        result.append({
            **r,
            "size_kb": size_kb,
            "exists": os.path.isfile(fp),
            "download_url": f"/proposals/{r['filename']}",
            "view_url": f"/proposals/{r['filename']}?inline=true",
        })
    return {"proposals": result}


