# Shared SSRF protection helper for Ollama-facing endpoints                     #
# ──────────────────────────────────────────────────────────────────────────── #
def _validate_ollama_url(url: str):
    """Return (base_url, None) if valid loopback URL, or (None, error_response)."""
    parsed = urlparse(url)
    hostname = parsed.hostname or ""
    allowed_hosts = {"localhost", "127.0.0.1", "::1"}
    try:
        ip = ipaddress.ip_address(hostname)
        if not ip.is_loopback:
            return None, JSONResponse(status_code=400, content={"connected": False, "error": "Only loopback/localhost URLs are allowed for security."})
    except ValueError:
        if hostname not in allowed_hosts:
            return None, JSONResponse(status_code=400, content={"connected": False, "error": "Only loopback/localhost URLs are allowed for security."})
    return url.rstrip("/"), None


